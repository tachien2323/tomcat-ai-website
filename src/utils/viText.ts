/**
 * Replaces spaces inside Vietnamese compound words with non-breaking spaces (\u00A0)
 * so browsers never break a compound word across lines on mobile or desktop.
 */
export function keepViCompounds(text: string): string {
  if (!text) return text;
  let result = text;
  for (const phrase of VI_COMPOUND_PHRASES) {
    const nbspPhrase = phrase.replace(/ /g, "\u00A0");
    result = result.split(phrase).join(nbspPhrase);
  }
  return result;
}
